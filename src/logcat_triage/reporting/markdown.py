"""Markdown rendering: paste-ready into Jira, GitHub issues or a PR comment."""

from __future__ import annotations

from logcat_triage.models import BugReport, TriageResult


def _cell(text: str | None) -> str:
    return (text or "-").replace("|", "\\|").replace("\n", " ")


def render_report(report: BugReport) -> str:
    """Render one bug report as a Markdown section."""
    out = [
        f"## BUG-{report.cluster_id}: {report.title}",
        "",
        f"- **Severity:** {report.severity} - {report.severity_rationale}",
        f"- **Occurrences:** {report.occurrence_count}",
        f"- **Affected packages:** {', '.join(report.affected_packages) or 'unknown'}",
        f"- **Kind:** {report.kind.value} (`{report.exception_type or 'n/a'}`)",
        f"- **First / last seen:** {report.first_seen or '?'} / {report.last_seen or '?'}",
        "",
        f"**Steps to reproduce** _({report.steps_label})_",
        "",
        *[f"{i}. {step}" for i, step in enumerate(report.steps_to_reproduce, start=1)],
        "",
        "**Stack trace (summary)**",
        "",
        "```text",
        report.stack_summary.strip(),
        "```",
        "",
        f"**Root-cause hypothesis:** {report.root_cause_hypothesis}",
        "",
    ]
    meta = f"Generated by `{report.generated_by}`"
    if report.latency_s is not None:
        meta += f" in {report.latency_s:.1f} s"
    if report.fallback_reason:
        meta += f" (fallback: {report.fallback_reason})"
    out += [f"_{meta}. Sample events: {', '.join(report.sample_event_ids)}_", ""]
    return "\n".join(out)


def render_markdown(result: TriageResult) -> str:
    """Render the whole triage result."""
    s = result.summary
    kinds = ", ".join(f"{k}: {v}" for k, v in s.events_by_kind.items()) or "none"
    lines = [
        "# Logcat triage report",
        "",
        f"- **Generated:** {s.generated_at}",
        f"- **Sources:** {', '.join(s.sources)} ({s.total_lines} lines)",
        f"- **Failures extracted:** {sum(s.events_by_kind.values())} ({kinds})",
        f"- **Clustering:** {s.clusters} clusters, embedder `{s.embedder}`, "
        f"cosine distance threshold {s.distance_threshold}",
    ]
    if s.embedder_fallback:
        lines.append(f"- **Embedder fallback:** {s.embedder_fallback}")
    lines += [f"- **Report writer:** {s.llm or 'heuristic (no LLM)'}", "", "## Clusters", ""]
    lines += ["| # | Kind | Exception / signal | Count | Packages |", "|---|---|---|---|---|"]
    for c in result.clusters:
        lines.append(
            f"| {c.id} | {c.kind.value} | {_cell(c.exception_type)} | {c.size} | "
            f"{_cell(', '.join(c.packages))} |"
        )
    lines.append("")
    for report in result.reports:
        lines.append(render_report(report))
    return "\n".join(lines).rstrip() + "\n"

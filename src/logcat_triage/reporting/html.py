def _e(text: object) -> str:
    return escape(str(text), quote=True)


def _report(report: BugReport, sample: FailureEvent | None) -> str:
    steps = "".join(f"<li>{_e(s)}</li>" for s in report.steps_to_reproduce)
    meta = f"Generated by {_e(report.generated_by)}"
    if report.latency_s is not None:
        meta += f" in {report.latency_s:.1f} s"
    if report.fallback_reason:
        meta += f" &middot; fallback: {_e(report.fallback_reason)}"
    raw = ""
    if sample is not None:
        raw = (
            f"<details><summary>Raw sample ({_e(sample.id)})</summary>"
            f"<pre><code>{_e(chr(10).join(sample.raw[:60]))}</code></pre></details>"
        )
    return f"""
<article id="bug-{report.cluster_id}">
  <div class="head"><span class="pill {_e(report.severity)}">{_e(report.severity)}</span>
  <h2>BUG-{report.cluster_id}: {_e(report.title)}</h2></div>
  <dl>
    <dt>Occurrences</dt><dd>{report.occurrence_count}</dd>
    <dt>Packages</dt><dd>{_e(", ".join(report.affected_packages) or "unknown")}</dd>
    <dt>Kind</dt><dd>{_e(report.kind.value)} &middot; <code>{_e(report.exception_type or "n/a")}</code></dd>
    <dt>Seen</dt><dd>{_e(report.first_seen or "?")} &rarr; {_e(report.last_seen or "?")}</dd>
    <dt>Severity</dt><dd>{_e(report.severity_rationale)}</dd>
  </dl>
  <h3>Steps to reproduce <span class="muted">({_e(report.steps_label)})</span></h3>
  <ol>{steps}</ol>
  <h3>Stack trace (summary)</h3>
  <pre><code>{_e(report.stack_summary.strip())}</code></pre>
  <h3>Root-cause hypothesis</h3>
  <p>{_e(report.root_cause_hypothesis)}</p>
  {raw}
  <footer>{meta}</footer>
</article>"""


def render_html(result: TriageResult) -> str:
    """Render the whole triage result as one HTML document."""
    s = result.summary
    events = {e.id: e for e in result.events}
    clusters_by_id = {c.id: c for c in result.clusters}
    rows = "".join(
        f"<tr><td>{c.id}</td><td>{_e(c.kind.value)}</td><td><code>{_e(c.exception_type or '-')}"
        f"</code></td><td>{c.size}</td><td>{_e(', '.join(c.packages) or '-')}</td></tr>"
        for c in result.clusters
    )
    reports = "".join(
        _report(r, events.get(clusters_by_id[r.cluster_id].representative_id))
        for r in result.reports
    )
    fallback = (
        f"<p class='muted'>Embedder fallback: {_e(s.embedder_fallback)}</p>"
        if s.embedder_fallback
        else ""
    )
    total = sum(s.events_by_kind.values())
    kinds = ", ".join(f"{k} {v}" for k, v in s.events_by_kind.items()) or "none"
    return f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>Logcat triage report</title><style>{_CSS}</style></head>
<body><main>
<h1>Logcat triage report</h1>
<p class="muted">{_e(s.generated_at)} &middot; {_e(", ".join(s.sources))} &middot; {s.total_lines} lines</p>
<section class="summary">
  <div class="stat"><b>{total}</b>failures extracted</div>
  <div class="stat"><b>{s.clusters}</b>clusters</div>
  <div class="stat"><b>{s.reports_generated}</b>bug reports</div>
  <div class="stat"><b>{_e(s.embedder)}</b>embedder (threshold {s.distance_threshold})</div>
</section>
<p class="muted">By kind: {_e(kinds)} &middot; report writer: {_e(s.llm or "heuristic (no LLM)")}</p>
{fallback}
<div class="table-wrap"><table><thead><tr><th>#</th><th>Kind</th><th>Exception / signal</th>
<th>Count</th><th>Packages</th></tr></thead><tbody>{rows}</tbody></table></div>
{reports}
</main></body></html>
"""

@pytest.mark.parametrize(
    "args",
    [
        ["devices"],
        ["devices", "-l"],
        ["logcat", "-d"],
        ["logcat", "-d", "-v", "threadtime", "-b", "crash", "-b", "main", "-t", "500"],
        ["-s", "emulator-5554", "logcat", "-d"],
    ],
)
def test_allowed_commands(args: list[str]) -> None:
    assert validate_args(args) == args


@pytest.mark.parametrize(
    "args",
    [
        [],
        ["shell", "rm", "-rf", "/"],
        ["install", "x.apk"],
        ["logcat"],
        ["logcat", "-d", "-c"],
        ["logcat", "-d", "-v", "raw"],
        ["logcat", "-d", "-b", "kernel"],
        ["logcat", "-d", "-t", "0"],
        ["logcat", "-d", "-t", "abc"],
        ["logcat", "-d", "-b"],
        ["devices", "; reboot"],
        ["-s", "bad serial;", "devices"],
        ["-s"],
    ],
)
def test_rejected_commands(args: list[str]) -> None:
    with pytest.raises(AdbError):
        validate_args(args)


def test_client_with_fake_transport(mixed_log_text: str) -> None:
    transport = FakeTransport(logcat_text=mixed_log_text, devices=("emulator-5554", "R5CT"))
    client = AdbClient(transport, serial="emulator-5554")
    assert client.list_devices() == ["emulator-5554", "R5CT"]
    assert client.dump_logcat(tail=1000) == mixed_log_text
    assert transport.calls[-1] == [
        "-s", "emulator-5554", "logcat", "-d", "-v", "threadtime",
        "-b", "main", "-b", "system", "-b", "crash", "-t", "1000",
    ]  # fmt: skip


def test_client_rejects_bad_serial_and_reports_failures() -> None:
    with pytest.raises(AdbError, match="serial"):
        AdbClient(FakeTransport(), serial="x; reboot")
    failing = FakeTransport(handler=lambda _args: CommandResult(1, "", "device offline"))
    with pytest.raises(AdbError, match="device offline"):
        AdbClient(failing).dump_logcat()


def test_fake_transport_from_file(tmp_path: Path) -> None:
    path = tmp_path / "x.logcat"
    path.write_text("hello\n", encoding="utf-8")
    assert AdbClient(FakeTransport.from_file(path)).dump_logcat() == "hello\n"


def test_subprocess_transport_uses_arg_list_without_shell(monkeypatch: pytest.MonkeyPatch) -> None:
    captured: dict[str, Any] = {}

    def fake_run(cmd: list[str], **kwargs: Any) -> subprocess.CompletedProcess[str]:
        captured["cmd"] = cmd
        captured.update(kwargs)
        return subprocess.CompletedProcess(cmd, 0, "List of devices attached\nabc\tdevice\n", "")

    monkeypatch.setattr(adb_module.shutil, "which", lambda _name: "/usr/bin/adb")
    monkeypatch.setattr(adb_module.subprocess, "run", fake_run)
    client = AdbClient(SubprocessTransport(), timeout=5)
    assert client.list_devices() == ["abc"]
    assert captured["cmd"] == ["/usr/bin/adb", "devices"]
    assert captured["shell"] is False
    assert captured["timeout"] == 5


def test_subprocess_transport_errors(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setattr(adb_module.shutil, "which", lambda _name: None)
    with pytest.raises(AdbError, match="not found"):
        SubprocessTransport()

    def slow(cmd: list[str], **kwargs: Any) -> None:
        raise subprocess.TimeoutExpired(cmd, 1)

    monkeypatch.setattr(adb_module.subprocess, "run", slow)
    transport = SubprocessTransport(adb_path="adb")
    with pytest.raises(AdbError, match="timed out"):
        transport.run(["devices"], timeout=1)
    with pytest.raises(AdbError, match="not allowed"):
        transport.run(["shell", "id"], timeout=1)
